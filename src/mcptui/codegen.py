def generate_claude_config_snippet(config: ServerConfig) -> str:
    """Generate Claude Desktop configuration JSON for this server."""
    entry: Dict[str, Any] = {}
    if config.transport == "sse":
        entry["url"] = config.url or ""
    else:
        entry["command"] = config.command or ""
        if config.args:
            entry["args"] = config.args
        if config.env:
            entry["env"] = config.env

    result = {
        "mcpServers": {
            config.name: entry
        }
    }
    return json.dumps(result, indent=2, ensure_ascii=False)


def generate_cursor_config_snippet(config: ServerConfig) -> str:
    """Generate Cursor mcp.json configuration for this server."""
    return generate_claude_config_snippet(config)


def generate_cli_snippet(
    config: ServerConfig,
    tool_name: Optional[str] = None,
    arguments: Optional[Dict[str, Any]] = None,
) -> str:
    """Generate headless mcptui call CLI command."""
    tool = tool_name or "my_tool"
    args = arguments if arguments is not None else {}
    compact_args = json.dumps(args)

    if config.source.startswith("local:"):
        return f'mcptui call {tool} \'{compact_args}\' --server {config.name}'
    elif config.transport == "stdio" and config.command:
        full_cmd = config.command
        if config.args:
            full_cmd += " " + " ".join(config.args)
        return f'mcptui call {tool} \'{compact_args}\' --cmd "{full_cmd}"'
    else:
        return f'mcptui call {tool} \'{compact_args}\' --server {config.name}'


def generate_jsonrpc_snippet(
    tool_name: Optional[str] = None,
    arguments: Optional[Dict[str, Any]] = None,
    msg_id: int = 1,
) -> str:
    """Generate raw JSON-RPC 2.0 payload."""
    tool = tool_name or "my_tool"
    args = arguments if arguments is not None else {}
    payload = {
        "jsonrpc": "2.0",
        "id": msg_id,
        "method": "tools/call",
        "params": {
            "name": tool,
            "arguments": args,
        },
    }
    return json.dumps(payload, indent=2, ensure_ascii=False)
